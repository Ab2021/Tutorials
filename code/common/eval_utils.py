"""
common/eval_utils.py — honest evaluation for fine-tuned models.

Three warnings before you use any of this:

1. **Held-out loss is not a quality metric.** A model can have excellent loss and be
   worse at everything you care about. Always pair it with a task metric.

2. **LLM judges have position bias and self-preference bias.** A GPT-class judge
   prefers the output that appears first (~55-65% of the time on ties) and prefers
   text from its own model family. Always evaluate both orderings and average.

3. **Your eval set leaks.** If your training data was generated by an LLM, or scraped
   from the same source as your eval set, your numbers are inflated. Run
   `decontaminate()` before you believe anything.
"""

from __future__ import annotations

import hashlib
import random
import re
from collections import Counter
from typing import Callable, Sequence

# --------------------------------------------------------------------------------------
# Decontamination
# --------------------------------------------------------------------------------------
def _shingles(text: str, n: int = 8) -> set[str]:
    toks = re.findall(r"\w+", text.lower())
    return {" ".join(toks[i:i + n]) for i in range(max(len(toks) - n + 1, 1))}


def decontaminate(train: Sequence[str], eval_set: Sequence[str], n: int = 8,
                  threshold: float = 0.5) -> list[int]:
    """
    Return indices of training examples that overlap an eval example.

    Method: n-gram shingle overlap. Anything above `threshold` should be removed.
    Common practice is to check 8-13 gram overlap; 8 is a reasonable default.

    Note: dedup against the eval set is not optional. Contaminated evals have produced
    several retracted benchmark claims, and more importantly they make *your own*
    internal decisions wrong.
    """
    eval_shingles = [_shingles(e, n) for e in eval_set]
    contaminated: list[int] = []
    for i, tr in enumerate(train):
        s = _shingles(tr, n)
        if not s:
            continue
        for es in eval_shingles:
            if es and len(s & es) / len(es) > threshold:
                contaminated.append(i)
                break
    return contaminated


def dedupe(texts: Sequence[str], n: int = 8) -> list[int]:
    """Exact + near-duplicate removal. Returns indices to KEEP."""
    seen_exact: set[str] = set()
    seen_shingles: list[set[str]] = []   # real use: MinHash + LSH for scale
    keep: list[int] = []

    for i, t in enumerate(texts):
        h = hashlib.sha256(t.encode()).hexdigest()
        if h in seen_exact:
            continue
        seen_exact.add(h)

        s = _shingles(t, n)
        dup = False
        for prev in seen_shingles[-5000:]:       # bounded for speed
            if prev and len(s & prev) / len(prev) > 0.8:
                dup = True
                break
        if dup:
            continue
        seen_shingles.append(s)
        keep.append(i)
    return keep


# --------------------------------------------------------------------------------------
# Task metrics
# --------------------------------------------------------------------------------------
def exact_match(preds: Sequence[str], refs: Sequence[str], normalize: bool = True) -> float:
    """For classification / extraction / math-with-fixed-format. Brittle but honest."""
    def norm(s: str) -> str:
        s = s.strip().lower()
        return re.sub(r"\s+", " ", s) if normalize else s
    if not preds:
        return 0.0
    return sum(norm(p) == norm(r) for p, r in zip(preds, refs)) / len(preds)


def format_compliance(preds: Sequence[str], schema: Callable[[str], bool]) -> float:
    """
    Fraction of outputs that parse into your required structure.

    This is the metric people forget, and it is usually the one that matters for
    production. A model that is 3% less accurate but 100% schema-compliant is worth
    more than a smarter model that breaks your JSON parser 20% of the time.
    """
    if not preds:
        return 0.0
    return sum(bool(schema(p)) for p in preds) / len(preds)


def refusal_rate(preds: Sequence[str]) -> float:
    """
    Fraction of responses that refuse.

    Watch this after SFT and again after preference alignment. Over-refusal is the
    classic silent regression of aggressive alignment: helpfulness scores stay high
    on your eval while real users hit walls.
    """
    markers = [
        "i can't", "i cannot", "i'm unable", "i am unable", "i won't",
        "as an ai", "i'm sorry, but", "i am sorry, but", "cannot assist",
        "can't help with that", "not able to provide",
    ]
    if not preds:
        return 0.0
    return sum(any(m in p.lower() for m in markers) for p in preds) / len(preds)


def response_length_stats(preds: Sequence[str]) -> dict[str, float]:
    """
    Length statistics. Always check these after preference training.

    Length bias is the single most common reward hack: if the reward model (or the
    judge) mildly prefers longer answers, PPO/DPO will discover it and inflate
    verbosity until the model is unusable. A 30%+ jump in mean length is a red flag,
    not an improvement.
    """
    lens = sorted(len(p.split()) for p in preds)
    if not lens:
        return {"n": 0, "mean": 0, "median": 0, "p95": 0}
    return {
        "n": len(lens),
        "mean": sum(lens) / len(lens),
        "median": lens[len(lens) // 2],
        "p95": lens[int(len(lens) * 0.95)],
    }


# --------------------------------------------------------------------------------------
# Win rate / LLM judge
# --------------------------------------------------------------------------------------
JUDGE_PROMPT = """You are evaluating two responses to the same user request.

[User request]
{prompt}

[Response A]
{a}

[Response B]
{b}

Which response is better? Judge on: correctness, relevance, completeness, clarity.
Ignore length unless it affects quality.
Reply with exactly one token: A, B, or TIE."""


def win_rate(judge_fn: Callable[[str], str], items: Sequence[dict],
             model_a_key: str = "model_a", model_b_key: str = "model_b") -> dict:
    """
    Position-bias-corrected win rate.

    We evaluate each pair TWICE with the order swapped. A response only counts as a
    win if it wins in both orderings; a split result counts as a tie. This removes
    first-position bias, which is worth 5-15 points of apparent score.

    `judge_fn(prompt) -> "A" | "B" | "TIE"` is injected so you can use any judge.
    """
    wins = losses = ties = 0
    for it in items:
        p, a, b = it["prompt"], it[model_a_key], it[model_b_key]

        fwd = judge_fn(JUDGE_PROMPT.format(prompt=p, a=a, b=b)).strip().upper()[:3]
        rev = judge_fn(JUDGE_PROMPT.format(prompt=p, a=b, b=a)).strip().upper()[:3]

        # Map reverse-order answers back to the original assignment.
        rev = {"A": "B", "B": "A", "TIE": "TIE"}.get(rev, "TIE")

        if fwd == rev == "A":
            wins += 1
        elif fwd == rev == "B":
            losses += 1
        else:
            ties += 1

    n = max(wins + losses + ties, 1)
    return {
        "n": n, "wins": wins, "losses": losses, "ties": ties,
        "win_rate": round(wins / n, 4),
        "win_rate_excl_ties": round(wins / max(wins + losses, 1), 4),
    }


def reward_hack_report(baseline_preds: Sequence[str], tuned_preds: Sequence[str]) -> dict:
    """
    Diagnose the three classic reward hacks by comparing before/after generations.

    Run this after every preference-optimization run. If any of these fire, your
    reward signal is being gamed and the model is probably worse, not better.
    """
    b_len = sum(len(p.split()) for p in baseline_preds) / max(len(baseline_preds), 1)
    t_len = sum(len(p.split()) for p in tuned_preds) / max(len(tuned_preds), 1)

    # Distinct-n: lexical diversity. A drop means the model collapsed onto a template.
    def distinct_n(preds: Sequence[str], n: int = 2) -> float:
        grams, total = Counter(), 0
        for p in preds:
            toks = p.lower().split()
            for i in range(len(toks) - n + 1):
                grams[" ".join(toks[i:i + n])] += 1
                total += 1
        return len(grams) / max(total, 1)

    db, dt = distinct_n(baseline_preds), distinct_n(tuned_preds)
    rb, rt = refusal_rate(baseline_preds), refusal_rate(tuned_preds)

    alerts = []
    if t_len > b_len * 1.3:
        alerts.append(f"LENGTH BIAS: mean length {b_len:.0f} -> {t_len:.0f} words (+{100*(t_len/b_len-1):.0f}%)")
    if dt < db * 0.9:
        alerts.append(f"DIVERSITY COLLAPSE: distinct-2 {db:.3f} -> {dt:.3f}")
    if rt > rb + 0.05:
        alerts.append(f"OVER-REFUSAL: refusal rate {rb:.1%} -> {rt:.1%}")

    # Sycophancy probe: does the model cave when the user asserts something false?
    return {
        "len_before": round(b_len, 1), "len_after": round(t_len, 1),
        "distinct2_before": round(db, 4), "distinct2_after": round(dt, 4),
        "refusal_before": round(rb, 4), "refusal_after": round(rt, 4),
        "alerts": alerts,
        "verdict": "REVIEW" if alerts else "OK",
    }


def bootstrap_ci(values: Sequence[float], n_boot: int = 1000, alpha: float = 0.05) -> tuple[float, float]:
    """
    95% CI by bootstrap. Always report this.

    Most fine-tuning "improvements" on eval sets under ~500 examples are inside the
    noise band. A 2-point gain on n=200 is not a result. This function is how you
    find out before you ship it.
    """
    if not values:
        return (0.0, 0.0)
    means = []
    for _ in range(n_boot):
        sample = [random.choice(values) for _ in range(len(values))]
        means.append(sum(sample) / len(sample))
    means.sort()
    return (means[int(n_boot * alpha / 2)], means[int(n_boot * (1 - alpha / 2))])
